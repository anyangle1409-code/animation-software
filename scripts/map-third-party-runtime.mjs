#!/usr/bin/env node
import fs from "node:fs";
import path from "node:path";

const ROOT=process.cwd();
const SRC=path.join(ROOT,"src");
const TARGETS=[
  "react",
  "react-dom",
  "three",
  "@react-three/fiber",
  "@react-three/drei",
  "zustand",
];

function walk(dir,out=[]){
  for(const ent of fs.readdirSync(dir,{withFileTypes:true})){
    const p=path.join(dir,ent.name);
    if(ent.isDirectory()) walk(p,out);
    else if(/\.(?:ts|tsx|js|jsx|mts|mjs)$/.test(ent.name)) out.push(p);
  }
  return out;
}

function classify(line){
  const hits=TARGETS.filter(t=>line.includes(t));
  return hits;
}

if(!fs.existsSync(SRC)){
  console.error("Missing src directory. Run from repository root.");
  process.exit(1);
}

const usage={};
for(const t of TARGETS) usage[t]=[];

for(const file of walk(SRC)){
  const rel=path.relative(ROOT,file).replaceAll("\\","/");
  const lines=fs.readFileSync(file,"utf8").split(/\r?\n/);
  lines.forEach((line,i)=>{
    for(const t of classify(line)){
      usage[t].push({file:rel,line:i+1,text:line.trim()});
    }
  });
}

const summary=Object.fromEntries(
  TARGETS.map(t=>[t,{
    matchCount:usage[t].length,
    files:[...new Set(usage[t].map(x=>x.file))].sort(),
  }])
);

const report={
  generatedAt:new Date().toISOString(),
  targets:TARGETS,
  summary,
  usage,
};

fs.mkdirSync(path.join(ROOT,"reports"),{recursive:true});
const jsonPath=path.join(ROOT,"reports","third_party_runtime_usage.json");
fs.writeFileSync(jsonPath,JSON.stringify(report,null,2)+"\n");

let md="# Runtime dependency usage map\n\n";
md+="Generated by `node scripts/map-third-party-runtime.mjs`.\n\n";
for(const t of TARGETS){
  md+=`## ${t}\n\n`;
  md+=`Matches: ${summary[t].matchCount}; files: ${summary[t].files.length}.\n\n`;
  if(summary[t].files.length){
    for(const f of summary[t].files) md+=`- \`${f}\`\n`;
  }else md+="- none found\n";
  md+="\n";
}
const mdPath=path.join(ROOT,"reports","third_party_runtime_usage.md");
fs.writeFileSync(mdPath,md);

console.log(JSON.stringify({
  json:path.relative(ROOT,jsonPath),
  markdown:path.relative(ROOT,mdPath),
  summary,
},null,2));
